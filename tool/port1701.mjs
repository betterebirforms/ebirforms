// Port BIR Form 1701's page logic mechanically (see src/form/form1701-sim.ts for why the native 1701 runs BIR's code).
//
//   node tool/port1701.mjs page <dir>   dir/{dom,ids,tables}-out.json → src/form/page/1701.json
//                                       (each = tool/port1701-capture.js's matching part, evaluated in BIR's blank
//                                       1701 opened in the oracle, test/oracle.ts — WebKit, legacy-shim.js served)
//   node tool/port1701.mjs port         vendor/original/forms/BIR-Form1701.hta + page/1701.json → src/form/form1701-bir.ts
//
// `port`: every function reachable from the main pages' inline handlers (plus the reload functions loadData calls)
// becomes a method of a class over the mini-DOM (form1701-dom.ts); every inline handler becomes (S, el) => {...}.
// Free identifiers → `this.X` (methods) / `S.X` (handlers), `this` in a handler → `el`, nested function expressions
// → arrows. BIR's sloppy-mode globals (`i`, `a`, …) are thereby fields of the sim, shared as in the browser.
import fs from "node:fs";
import { parseAst } from "rolldown/parseAst";

const ROOT_DIR = new URL("..", import.meta.url).pathname;
const PAGE = `${ROOT_DIR}src/form/page/1701.json`;
const HTA = `${ROOT_DIR}vendor/original/forms/BIR-Form1701.hta`;
const OUT = `${ROOT_DIR}src/form/form1701-bir.ts`;
/** loadData's own calls (not reachable from a handler) */
const RELOAD = ["HidePage12Part9", "disableEnableFieldsOnReload", "validateModalState", "validateAttachmentPerson"];

if (process.argv[2] === "page") page(process.argv[3]);
else if (process.argv[2] === "port") port();
else console.error("usage: node tool/port1701.mjs page <capture-dir> | port");

function page(dir) {
  const read = (n) => { const j = JSON.parse(fs.readFileSync(`${dir}/${n}-out.json`, "utf8")); return j.result ?? j; };
  const anc = [], ancIx = new Map(), handler = [], hIx = new Map();
  const ai = (s) => { if (!ancIx.has(s)) { ancIx.set(s, anc.length); anc.push(s); } return ancIx.get(s); };
  const hi = (s) => { if (!s) return -1; if (!hIx.has(s)) { hIx.set(s, handler.length); handler.push(s); } return hIx.get(s); };
  const el = read("dom").el.map((e) => [e.id, e.type, e.name, e.cls, e.ml ?? "", e.dis ? 1 : 0, e.v, e.chk ? 1 : 0, ai(e.anc), hi(e.blur), hi(e.click), hi(e.change), e.inForm ? 1 : 0, e.vis ? 1 : 0]);
  const note = "BIR Form 1701's blank page, measured in WebKit. el: every input/select/textarea in DOM order [id, type, name, class, maxlength, disabled, value, checked, ancestor-ids index, onblur, onclick, onchange (index into handler / form1701-bir.ts HANDLER, -1 none), in frmMain, visible (page 1 showing)]; box: every other element id ('tag id'); table: each table's rows (first child id per cell, inputs); handler: the inline handler attributes. Generated by tool/port1701.mjs page.";
  const j = JSON.stringify;
  const text = `{\n"note": ${j(note)},\n"anc": [\n${anc.map((a) => j(a)).join(",\n")}\n],\n"box": ${j(read("ids"))},\n"table": ${j(read("tables"))},\n"handler": [\n${handler.map((h) => j(h)).join(",\n")}\n],\n"el": [\n${el.map((a) => j(a)).join(",\n")}\n]\n}\n`;
  fs.writeFileSync(PAGE, text);
  console.error("el", el.length, "anc", anc.length, "handler", handler.length, "bytes", text.length);
}

/** index just past the brace matching the "{" at i, skipping strings, comments and regex literals */
function matchBrace(src, i) {
  let depth = 0;
  let prev = "";
  for (let j = i; j < src.length; j++) {
    const c = src[j];
    const n = src[j + 1];
    if (c === "/" && n === "/") { j = src.indexOf("\n", j); if (j < 0) return src.length; continue; }
    if (c === "/" && n === "*") { j = src.indexOf("*/", j + 2) + 1; continue; }
    if (c === "'" || c === '"' || c === "`") {
      for (j++; j < src.length && src[j] !== c; j++) if (src[j] === "\\") j++;
      prev = "a";
      continue;
    }
    if (c === "/" && /[(,=:[!&|?{};]/.test(prev)) {
      let inClass = false;
      for (j++; j < src.length; j++) {
        if (src[j] === "\\") { j++; continue; }
        if (src[j] === "[") inClass = true;
        else if (src[j] === "]") inClass = false;
        else if (src[j] === "/" && !inClass) break;
      }
      prev = "a";
      continue;
    }
    if (c === "{") depth++;
    else if (c === "}") { depth--; if (depth === 0) return j + 1; }
    if (!/\s/.test(c)) prev = c;
  }
  return src.length;
}

/** BIR's named functions (the first definition of a name wins, as the scoreboard measured) */
function functions(src) {
  const fn = new Map();
  const re = /\bfunction\s+([A-Za-z_$][\w$]*)\s*\(([^)]*)\)\s*\{/g;
  let m;
  while ((m = re.exec(src))) {
    const open = m.index + m[0].length - 1;
    const end = matchBrace(src, open);
    if (!fn.has(m[1])) fn.set(m[1], { params: m[2].split(",").map((s) => s.trim()).filter(Boolean), body: src.slice(open + 1, end - 1), start: m.index });
    re.lastIndex = end;
  }
  return fn;
}

function port() {
  const hta = fs.readFileSync(HTA, "utf8").split("\n");
  // the scripts after the markup, up to the eFPS connection block (lines 21120–38320 of v7.9.6.2)
  const from = hta.indexOf("</body>");
  const to = hta.indexOf("<!-- eFPS Connection -->", from);
  const fn = functions(hta.slice(from, to < 0 ? undefined : to).join("\n"));
  const dom = JSON.parse(fs.readFileSync(PAGE, "utf8"));
  const BUILTIN = new Set("undefined,NaN,Infinity,Math,parseInt,parseFloat,isNaN,String,Number,Array,Object,Date,RegExp,escape,unescape,isFinite,arguments,console".split(","));
  const isMain = (anc) => /\b(Page\d+Content|tblPart7A)\b/.test(anc);
  const hMain = new Set();
  for (const e of dom.el) for (const h of [e[9], e[10], e[11]]) if (h >= 0 && isMain(dom.anc[e[8]])) hMain.add(h);

  const walk = (n, cb, parent, key) => {
    if (!n || typeof n.type !== "string") return;
    cb(n, parent, key);
    for (const k of Object.keys(n)) {
      if (k === "start" || k === "end") continue;
      const v = n[k];
      if (Array.isArray(v)) v.forEach((c) => c && typeof c === "object" && walk(c, cb, n, k));
      else if (v && typeof v === "object" && typeof v.type === "string") walk(v, cb, n, k);
    }
  };
  const rewrite = (text, owner, prefix, thisTo, calls) => {
    const root = parseAst(text).body[0];
    const declared = new Set(root.params.map((p) => p.name));
    walk(root.body, (n) => {
      if (n.type === "VariableDeclarator" && n.id.type === "Identifier") declared.add(n.id.name);
      if (n.type === "FunctionDeclaration" || n.type === "FunctionExpression") {
        if (n.id) declared.add(n.id.name);
        for (const p of n.params) if (p.type === "Identifier") declared.add(p.name);
      }
      if (n.type === "CatchClause" && n.param) declared.add(n.param.name);
    });
    const edit = [];
    walk(root.body, (n, parent, key) => {
      if (n.type === "ThisExpression" && thisTo) edit.push([n.start, n.end, thisTo]);
      if (n.type !== "Identifier") return;
      if (parent?.type === "MemberExpression" && key === "property" && !parent.computed) return;
      if (parent?.type === "Property" && key === "key" && !parent.computed) return;
      if (parent?.type === "VariableDeclarator" && key === "id") return;
      if (parent?.type === "FunctionExpression" || parent?.type === "FunctionDeclaration" || parent?.type === "CatchClause") return;
      if (declared.has(n.name) || BUILTIN.has(n.name)) return;
      edit.push([n.start, n.end, prefix + n.name]);
      if (fn.has(n.name)) calls.add(n.name);
    });
    walk(root.body, (n) => {
      if (n.type !== "FunctionExpression") return;
      if (/\bthis\b/.test(text.slice(n.body.start, n.body.end))) console.error("nested `this` in", owner);
      edit.push([n.start, n.body.start, `(${n.params.map((p) => text.slice(p.start, p.end) + ": any").join(", ")}) => `]);
    });
    edit.sort((a, b) => b[0] - a[0] || b[1] - a[1]);
    let out = text;
    let last = Infinity;
    for (const [s, e, r] of edit) {
      if (e > last) throw new Error(`overlapping edit in ${owner}`);
      out = out.slice(0, s) + r + out.slice(e);
      last = s;
    }
    return out;
  };

  const seed = new Set(RELOAD);
  const hOut = dom.handler.map((s, i) => {
    if (!hMain.has(i)) return "null";
    const calls = new Set();
    const body = rewrite(`function __h() {${s}\n}`, `handler#${i}`, "S.", "el", calls);
    for (const c of calls) seed.add(c);
    return "(S, el) => {" + body.replace(/^function __h\(\) \{/, "").replace(/\n\}$/, "") + "\n}";
  });
  const done = new Map();
  const q = [...seed];
  while (q.length) {
    const name = q.shift();
    if (done.has(name) || !fn.has(name)) continue;
    const f = fn.get(name);
    const calls = new Set();
    const body = rewrite(`function ${name}(${f.params.join(", ")}) {${f.body}}`, name, "this.", null, calls);
    done.set(name, body.replace(/^function (\w+)\(([^)]*)\)/, (_, n, p) => `${n}(${p.split(",").map((x) => x.trim()).filter(Boolean).map((x) => x + "?: any").join(", ")}): any`));
    q.push(...calls);
  }
  const names = [...done.keys()].sort((a, b) => fn.get(a).start - fn.get(b).start);
  let out = `// @ts-nocheck — GENERATED by tool/port1701.mjs from BIR's own page script (BIR-Form1701.hta); see form1701-dom.ts.
// BIR's JavaScript is untyped and relies on sloppy-mode globals (\`i\`, \`a\`, … are shared across functions, kept as
// fields of the sim); the code below is that JavaScript, mechanically rebound to the mini-DOM — not hand-edited.
/* eslint-disable */
import { Dom1701 } from "./form1701-dom.ts";

export class Bir1701 extends Dom1701 {\n`;
  for (const n of names) out += `  // BIR ${n}\n  ` + done.get(n).replace(/\n/g, "\n  ") + "\n\n";
  out += `}\n\n/** BIR's inline onblur / onclick / onchange attributes (index = page/1701.json handler index), \`this\` = the element. */\nexport const HANDLER: Array<((S: Bir1701, el: any) => void) | null> = [\n${hOut.join(",\n")}\n];\n`;
  fs.writeFileSync(OUT, out);
  console.error("methods", names.length, "handlers", hMain.size, "/", dom.handler.length, "lines", out.split("\n").length);
}
